#!/usr/bin/env node
/**
 * Writes `lib/tech-icons.ts` with only the brand marks the stack grid uses.
 *
 * `simple-icons` ships ~3000 icons; importing it from a client component would
 * put all of them in the bundle. Extracting the handful we need at build time
 * keeps it to a few kilobytes and removes the runtime dependency entirely —
 * which is why `simple-icons` is a devDependency.
 *
 * Usage: node scripts/generate-tech-icons.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Stack label → simple-icons slug. Java resolves to OpenJDK: Oracle's Java
 *  mark is not redistributable, and OpenJDK is what the work actually runs on. */
const BRANDS = {
  Java: "openjdk",
  Kotlin: "kotlin",
  Python: "python",
  "Spring Boot": "spring",
  Quarkus: "quarkus",
  AWS: "amazonwebservices",
  Kubernetes: "kubernetes",
  Terraform: "terraform",
  Docker: "docker",
  Angular: "angular",
  React: "react",
  TypeScript: "typescript",
};

/**
 * Some brand colours are unusable as a hover tint on a black page: OpenJDK is
 * #000000, Angular #0F0F11 and the AWS wordmark #232F3E. These are the marks'
 * other official colours, which stay recognisable against the dark ground.
 */
const HEX_OVERRIDES = {
  Java: "E76F00",
  Angular: "E23237",
  AWS: "FF9900",
};

/** No brand exists for these, so they are drawn by hand as line icons. */
const CUSTOM = {
  LLMs: {
    hex: "9CA3AF",
    stroke: true,
    body: [
      '<circle cx="5" cy="6.5" r="1.6"/>',
      '<circle cx="5" cy="12" r="1.6"/>',
      '<circle cx="5" cy="17.5" r="1.6"/>',
      '<circle cx="12.5" cy="9" r="1.6"/>',
      '<circle cx="12.5" cy="15" r="1.6"/>',
      '<circle cx="19.5" cy="12" r="1.6"/>',
      '<path d="M6.5 6.9 11 8.6M6.5 11.7 11 9.6M6.5 12.4 11 14.4M6.5 17.1 11 15.4M14 9.4l4 1.9M14 14.6l4-1.9"/>',
    ].join(""),
  },
  "AI Agents": {
    hex: "9CA3AF",
    stroke: true,
    body: [
      '<path d="M12 2.6 20 7v10l-8 4.4L4 17V7z"/>',
      '<circle cx="12" cy="12" r="2.7"/>',
      '<path d="M12 2.6v6.7M12 14.7v6.7M4 7l5.6 3.6M20 7l-5.6 3.6"/>',
    ].join(""),
  },
  RAG: {
    hex: "9CA3AF",
    stroke: true,
    body: [
      '<path d="M6.5 3h6.2L18 8v12a1.6 1.6 0 0 1-1.6 1.6H6.5A1.6 1.6 0 0 1 4.9 20V4.6A1.6 1.6 0 0 1 6.5 3z"/>',
      '<path d="M12.4 3v5.2h5.2"/>',
      '<circle cx="10.4" cy="14.2" r="2.7"/>',
      '<path d="m12.5 16.3 2.4 2.4"/>',
    ].join(""),
  },
};

const entries = [];

for (const [label, slug] of Object.entries(BRANDS)) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const icon = simpleIcons[key];
  if (!icon) throw new Error(`simple-icons has no "${slug}" (looked up ${key})`);
  const hex = HEX_OVERRIDES[label] ?? icon.hex;
  entries.push({ label, hex, stroke: false, body: `<path d="${icon.path}"/>` });
}

for (const [label, icon] of Object.entries(CUSTOM)) {
  entries.push({ label, hex: icon.hex, stroke: true, body: icon.body });
}

const file = `// Generated by scripts/generate-tech-icons.mjs — do not edit by hand.
// Brand marks come from simple-icons; the three AI entries are drawn here
// because no brand exists for them.

export type TechIcon = {
  /** Brand colour, used only on hover — the grid is monochrome at rest. */
  hex: string;
  /** Inner markup for a 24x24 viewBox. */
  body: string;
  /** Line icons paint with stroke; brand marks with fill. */
  stroke: boolean;
};

export const techIcons: Record<string, TechIcon> = {
${entries
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.label)}: {\n    hex: "#${entry.hex}",\n    stroke: ${entry.stroke},\n    body: ${JSON.stringify(entry.body)},\n  },`,
  )
  .join("\n")}
};
`;

writeFileSync(resolve(ROOT, "lib/tech-icons.ts"), file);
process.stderr.write(`wrote lib/tech-icons.ts with ${entries.length} icons\n`);
